#include <iostream>
using namespace std;
int main() {

    // BITWISE OPERATORS

    cout<<(3 & 5) << endl;
    cout<<(3 | 5) << endl;
    cout<<(3 ^ 5) << endl;
    

    // BINARY NOT  OPERATOR

    cout << (~6) << endl; 
    cout << (~0 )<< endl; 

    // BINARY SHIFT OPERTORS
    cout << (7 >> 2) << endl;

    return 0;
}
